import type { Lesson } from '../types/wordbook';

type WordSeed = [word: string, phonetic: string, translation: string, exampleEn: string, exampleZh: string];
type SentenceSeed = [en: string, zh: string, notes?: string];
type DialogueSeed = [speaker: 'A' | 'B', en: string, zh: string];
type PromptSeed = [en: string, zh: string];

function daily(
  order: number,
  title: string,
  subtitle: string,
  words: WordSeed[],
  sentences: SentenceSeed[],
  dialogue: DialogueSeed[],
  prompts: PromptSeed[],
): Lesson {
  const id = `d${order}`;
  return {
    id,
    track: 'daily',
    order,
    week: Math.ceil(order / 5),
    title,
    subtitle,
    words: words.map(([word, phonetic, translation, en, zh], index) => ({
      id: `${id}-w${String(index + 1).padStart(2, '0')}`,
      word,
      phonetic,
      translation,
      category: 'daily',
      examples: [{ en, zh }],
    })),
    sentences: sentences.map(([en, zh, notes], index) => ({
      id: `${id}-s${String(index + 1).padStart(2, '0')}`,
      en,
      zh,
      ...(notes ? { notes } : {}),
    })),
    dialogue: dialogue.map(([speaker, en, zh]) => ({ speaker, en, zh })),
    practicePrompts: prompts.map(([en, zh]) => ({ en, zh })),
  };
}

